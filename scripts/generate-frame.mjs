// Generate a simple placeholder PNG frame for the photobooth
// Run with: node scripts/generate-frame.mjs

import { writeFileSync } from 'fs';

// We'll create a minimal valid 1x1 transparent PNG as placeholder
// The real frame should be designed and replaced by the team
// For now, the photobooth component handles missing frames gracefully

// Minimal 1x1 transparent PNG (68 bytes)
const transparentPNG = Buffer.from([
  0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a, // PNG signature
  0x00, 0x00, 0x00, 0x0d, 0x49, 0x48, 0x44, 0x52, // IHDR chunk
  0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00, 0x01, // 1x1
  0x08, 0x06, 0x00, 0x00, 0x00, 0x1f, 0x15, 0xc4, // RGBA
  0x89, 0x00, 0x00, 0x00, 0x0a, 0x49, 0x44, 0x41, // IDAT chunk
  0x54, 0x78, 0x9c, 0x62, 0x00, 0x00, 0x00, 0x02, // compressed data
  0x00, 0x01, 0xe5, 0x27, 0xde, 0xfc, 0x00, 0x00, // ...
  0x00, 0x00, 0x49, 0x45, 0x4e, 0x44, 0xae, 0x42, // IEND chunk
  0x60, 0x82
]);

writeFileSync('public/frames/haxtreme-frame.png', transparentPNG);
console.log('✅ Placeholder frame created at public/frames/haxtreme-frame.png');
console.log('⚠️  Replace this with your actual 1080x1080 transparent PNG frame!');
